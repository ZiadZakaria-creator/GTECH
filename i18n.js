// ============ التشغيل ============
const LANG = (() => {
  let l = "ar";
  try {
    l = new URLSearchParams(location.search).get("lang") || localStorage.getItem("gtech-lang") || "ar";
    if (l !== "en") l = "ar";
    localStorage.setItem("gtech-lang", l);
  } catch {}
  return l;
})();
const IS_EN = LANG === "en";

const AR_RE = /[؀-ۿ]/;
const I18N_RX = IS_EN ? I18N_PATTERNS.map(([rx, en]) => [new RegExp(rx), en]) : [];
const toLatin = (s) => s.replace(/[٠-٩]/g, (d) => "٠١٢٣٤٥٦٧٨٩".indexOf(d)).replace(/٬/g, ",").replace(/٫/g, ".");

// ترجمة جملة واحدة (بنفس شكلها بالظبط، أو بنمط فيه متغيرات)
function tr(s) {
  if (!IS_EN || !s || !AR_RE.test(s)) return s;
  const key = s.replace(/\s+/g, " ").trim();
  if (I18N_EN[key] !== undefined) return I18N_EN[key];
  const sep = key.match(/^([·•|—–-]\s*)(.+)$/); // "· كيبوردات من" ← فاصل قبل الجملة
  if (sep && AR_RE.test(sep[2])) { const t = tr(sep[2]); if (t !== sep[2]) return sep[1] + t; }
  for (const [rx, en] of I18N_RX) {
    const m = key.match(rx);
    if (!m) continue;
    const parts = m.slice(1).map((g) => tr(toLatin(g || "")));
    // جملة قصيرة زي "لحد {}" ماينفعش تترجم نص كلام المنتج ("لحد 40 ساعة") ويفضل الباقي عربي.
    // الأسماء بس (اسم العميل أو المنتج، ومكتوبة بين "" أو بعد أهلاً) مسموح تفضل عربي
    if (parts.some((g) => AR_RE.test(g)) && !/"\{\d\}"|^(?:Hi|✔ Number verified|Name:)/.test(en)) continue;
    return en.replace(/\{(\d)\}/g, (_, i) => parts[i - 1]);
  }
  return s;
}

if (IS_EN) {
  const html = document.documentElement;
  html.lang = "en";
  html.dir = "ltr";
  // نخفي الصفحة لحظة لحد ما تتترجم عشان العربي مايبانش ويختفي
  const hide = document.createElement("style");
  hide.textContent = "body{visibility:hidden}";
  document.head.appendChild(hide);
  const reveal = () => hide.remove();
  setTimeout(reveal, 1500);

  const ATTRS = ["placeholder", "aria-label", "title", "alt"];
  const SKIP = new Set(["SCRIPT", "STYLE", "NOSCRIPT", "TEXTAREA"]);
  const doText = (n) => {
    const v = n.nodeValue;
    if (!AR_RE.test(v) || SKIP.has(n.parentNode?.nodeName)) return;
    const t = v.trim();
    const out = tr(t);
    if (out !== t) n.nodeValue = v.replace(t, out);
  };
  const doEl = (el) => {
    if (el.closest?.("[data-no-i18n]")) return;
    for (const a of ATTRS) {
      const v = el.getAttribute?.(a);
      if (v && AR_RE.test(v)) { const out = tr(v); if (out !== v) el.setAttribute(a, out); }
    }
  };
  const walk = (root) => {
    if (root.nodeType === 3) return doText(root);
    if (root.nodeType !== 1 || SKIP.has(root.nodeName) || root.closest?.("[data-no-i18n]")) return;
    doEl(root);
    const it = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
    let n;
    while ((n = it.nextNode())) (n.nodeType === 3 ? doText(n) : doEl(n));
  };
  new MutationObserver((list) => {
    for (const m of list) {
      if (m.type === "characterData") doText(m.target);
      else if (m.type === "attributes") doEl(m.target);
      else m.addedNodes.forEach(walk);
    }
  }).observe(html, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ATTRS });
  document.addEventListener("DOMContentLoaded", () => { walk(html); reveal(); });

  // رسايل المتصفح (تأكيد المسح مثلاً)
  const conf = window.confirm.bind(window), al = window.alert.bind(window);
  window.confirm = (m) => conf(tr(m));
  window.alert = (m) => al(tr(m));
}

// ============ زرار تغيير اللغة ============
function setLang(l) {
  try { localStorage.setItem("gtech-lang", l); } catch {}
  const u = new URL(location.href);
  u.searchParams.delete("lang");
  // لو اللينك هو هو (أو بيفرق في #products بس) المتصفح مش بيعيد التحميل ← نعيده إحنا
  const same = u.origin + u.pathname + u.search === location.origin + location.pathname + location.search;
  if (same) location.reload();
  else location.replace(u.toString());
}
